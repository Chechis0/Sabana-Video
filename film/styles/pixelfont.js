// tildes: acento agudo sobre la letra base (dos filas por encima)
const ACUTE = { á: 'a', é: 'e', í: 'i', ó: 'o', ú: 'u', Á: 'A', É: 'E', Í: 'I', Ó: 'O', Ú: 'U' };
const TILDE = { ñ: 'n', Ñ: 'N' };

const DOTLESS_I = ['..', '..', '#.', '#.', '#.', '#.', '#.'];
function glyph(ch) {
  if (ch === 'í') return { rows: DOTLESS_I, mark: 'acute', upper: false };
  if (G[ch]) return { rows: G[ch], mark: null };
  if (ACUTE[ch]) return { rows: G[ACUTE[ch]], mark: 'acute', upper: ACUTE[ch] === ACUTE[ch].toUpperCase() };
  if (TILDE[ch]) return { rows: G[TILDE[ch]], mark: 'tilde', upper: TILDE[ch] === TILDE[ch].toUpperCase() };
  return { rows: G['?'], mark: null };
}

// mapa de bits de una línea: devuelve {w, h, on(x,y)} con 2 filas extra arriba para tildes
export function layout(str, spacing = 1) {
  const cols = [];
  let x = 0;
  const pix = [];
  for (const ch of str) {
    const { rows, mark, upper } = glyph(ch);
    const gw = rows[0].length;
    rows.forEach((r, y) => { for (let i = 0; i < gw; i++) if (r[i] === '#') pix.push([x + i, y + 2, ch]); });
    if (mark) {
      // minúsculas: tilde justo encima de la x-altura (filas 2–3); mayúsculas: sobre la letra (0–1)
      const r0 = upper ? 0 : 2;
      const cx = Math.floor(gw / 2);
      if (ch === 'í') pix.push([x + 1, r0, ch], [x, r0 + 1, ch]);
      else if (mark === 'acute') pix.push([x + cx + 1, r0, ch], [x + cx, r0 + 1, ch]);
      else pix.push([x + 1, r0, ch], [x + 3, r0, ch], [x, r0 + 1, ch], [x + 2, r0 + 1, ch]);
    }
    cols.push({ ch, x, w: gw });
    x += gw + spacing;
  }
  return { w: Math.max(0, x - spacing), h: 11, pix, cols };
}

// pinta texto en la cuadrícula: (cx, top) en píxeles pequeños, centrado en cx.
// k: progreso de aparición (letra por letra); o: { scale, color, outline, shadow, bounce }
export function pixelText(ctx, str, cx, top, k, o = {}) {
  const s = o.scale ?? 1;
  const L = layout(str, o.spacing ?? 1);
  const x0 = Math.round(cx - (L.w * s) / 2);
  const n = L.cols.length;
  const shown = Math.floor(k * (n + 0.999));
  if (shown <= 0) return L;
  // qué letras se ven (y cuál acaba de aparecer: rebota un píxel)
  const visible = new Set();
  const colOf = new Map();
  L.cols.forEach((c, i) => { if (i < shown) visible.add(c.x); colOf.set(c.x, i); });
  const charIndex = (px) => { let idx = -1; for (const c of L.cols) { if (px >= c.x - 1 && px < c.x + c.w + 1) idx = colOf.get(c.x); } return idx; };
  const on = new Map();
  for (const [x, y] of L.pix) {
    const idx = charIndex(x);
    if (idx < 0 || idx >= shown) continue;
    const jump = o.bounce !== false && idx === shown - 1 && k < 1 ? -1 : 0;
    on.set(x + ',' + (y + jump), [x, y + jump]);
  }
  const P = PX;
  const rect = (x, y, col) => { ctx.fillStyle = col; ctx.fillRect((x0 + x * s) * P, (top + y * s) * P, s * P, s * P); };
  ctx.save();
  ctx.setTransform(1, 0, 0, 1, 0, 0);
  ctx.globalAlpha = o.alpha ?? 1;
  ctx.globalCompositeOperation = 'source-over';
  // sombra (1 píxel abajo-derecha) y contorno (8 vecinos)
  if (o.shadow !== false) for (const [x, y] of on.values()) rect(x + 1, y + 1 + (o.outline ? 1 : 0), o.shadow || 'rgba(20,16,30,0.55)');
  if (o.outline) {
    for (const [x, y] of on.values()) {
      for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if (!on.has((x + dx) + ',' + (y + dy))) rect(x + dx, y + dy, o.outline);
    }
  }
  for (const [x, y] of on.values()) rect(x, y, o.color || '#ffffff');
  // brillo arriba de cada letra (dos tonos, como los títulos de los juegos)
  if (o.hi) for (const [x, y] of on.values()) if (!on.has(x + ',' + (y - 1))) rect(x, y, o.hi);
  ctx.restore();
  return L;
}

export function textWidth(str, scale = 1, spacing = 1) { return layout(str, spacing).w * scale; }
